// shortcut: 문맥 없는 이름과 변형된 개인정보는 탐지하지 못할 수 있어, 로컬 개인정보 인식기가 준비되면 교체한다.
export function filterModerationText(body: string) {
  let hasContact = false;
  const contact = () => {
    hasContact = true;
    return '[연락처]';
  };
  const text = body.normalize('NFKC')
    .replace(/[\w.+-]+\s*(?:@|\(at\)|\[at\])\s*[\w.-]+\s*(?:\.|\(dot\)|\[dot\])\s*[a-zA-Z]{2,}/gi, contact)
    .replace(/(?:https?:\/\/|www\.)[^\s]+/gi, contact)
    .replace(/(?:카카오톡|카톡|인스타그램|인스타|텔레그램|라인|SNS|아이디|계정)\s*(?:아이디|ID|계정|은|는|이|가|:|：)?\s*[@]?[a-zA-Z0-9_.-]{3,}/gi, contact)
    .replace(/(?<![\w])@[a-zA-Z0-9_.]{2,}/g, contact)
    .replace(/(?<!\d)\d{6}\s*[- ]\s*[1-8]\d{6}(?!\d)/g, '[식별번호]')
    .replace(/(?<!\d)(?:\+?82[\s.()\-]*|0)(?:1[016789]|2|[3-6][1-5])[\s.()\-]*\d{3,4}[\s.()\-]*\d{4}(?!\d)/g, contact)
    .replace(/(?<!\d)0[\s.()\-]*1[\s.()\-]*[016789](?:[\s.()\-]*\d){7,8}(?!\d)/g, contact)
    .replace(/(?<![가-힣\d])(?:공|영|0)\s*(?:일|1)\s*(?:공|영|0)(?:[\s.()\-]*(?:공|영|일|이|삼|사|오|육|륙|칠|팔|구|[0-9])){7,8}(?![가-힣\d])/g, contact)
    .replace(/(?<!\d)(?:\d[\s-]*){13,19}(?!\d)/g, '[식별번호]')
    .replace(/(?:[가-힣]+(?:특별시|광역시|특별자치시|특별자치도|도|시|군|구)\s*)?(?:[가-힣\d]+(?:시|군|구|읍|면|동|리)\s*)*(?:[가-힣\d]+(?:로|길)\s*\d+(?:-\d+)?(?:\s*\d+동)?(?:\s*\d+호)?|[가-힣\d]+(?:동|리)\s*\d+(?:-\d+)?(?:\s*\d+호)?)/g, '[주소]')
    .replace(/((?:주소|거주지|집주소)\s*(?:은|는|이|가|:|：)\s*)[^,\n.!?]+/g, '$1[주소]')
    .replace(/((?:이름|성명|본명)\s*(?:은|는|이|가|:|：)?\s*)[가-힣]{2,4}/g, '$1[이름]')
    .replace(/((?:저는|나는|제\s*이름은|내\s*이름은)\s+)[가-힣]{2,4}(?=(?:입니다|이에요|예요|이라고|이라|[\s,.!?]|$))/g, '$1[이름]')
    .replace(/[가-힣]{2,4}(?=\s*(?:님|씨)(?:[\s,.!?]|$))/g, '[이름]')
    .replace(/(?<![가-힣])(?!오늘도(?:[\s,.!?]|$))(?:남궁|황보|제갈|선우|서문|독고|사공|김|이|박|최|정|강|조|윤|장|임|한|오|서|신|권|황|안|송|전|홍|고|문|양|손|배|백|허|남|심|노|하|곽|성|차|주|우|구|민|진|지|엄|채|원|천|방|공|현|함|변|염|여|추|도|소|석|선|설|마|길|연|위|표|명|기|반|왕|금|옥|육|인|맹|제|모|탁|국|어|은|편|용|예|봉|사|부|가|복|태|목|형|계|피|두|감|동|온|빈)[가-힣]{2}(?=(?:은|는|이|가|을|를|의|와|과|에게|한테|이라고|입니다|이에요|예요)?(?:[\s,.!?]|$))/g, '[이름]');
  return { text, hasContact };
}
