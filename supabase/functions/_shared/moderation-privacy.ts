// shortcut: 문맥 없는 이름("홍길동이 힘들어요")과 변형된 개인정보는 탐지하지 못한다. 로컬 개인정보 인식기가 준비되면 교체한다.
export function filterModerationText(body: string) {
  let hasContact = false;
  const contact = () => {
    hasContact = true;
    return '[연락처]';
  };
  const text = body.normalize('NFKC')
    .replace(/[\w.+-]+\s*(?:@|\(at\)|\[at\])\s*[\w.-]+\s*(?:\.|\(dot\)|\[dot\])\s*[a-zA-Z]{2,}/gi, contact)
    .replace(/(?:https?:\/\/|www\.)[^\s]+/gi, contact)
    .replace(/(?:카카오톡|카톡|인스타그램|인스타|텔레그램|라인|SNS|아이디|계정)\s*(?:아이디|ID|계정|은|는|이|가|:|：)?\s*[@]?[a-zA-Z0-9_.-]{3,}/gi, contact)
    .replace(/(?<![\w])@[a-zA-Z0-9_.]{2,}/g, contact)
    .replace(/(?<!\d)\d{6}\s*[- ]\s*[1-8]\d{6}(?!\d)/g, '[식별번호]')
    .replace(/(?<!\d)(?:\+?82[\s.()\-]*|0)(?:1[016789]|2|[3-6][1-5])[\s.()\-]*\d{3,4}[\s.()\-]*\d{4}(?!\d)/g, contact)
    .replace(/(?<!\d)0[\s.()\-]*1[\s.()\-]*[016789](?:[\s.()\-]*\d){7,8}(?!\d)/g, contact)
    .replace(/(?<![가-힣\d])(?:공|영|0)\s*(?:일|1)\s*(?:공|영|0)(?:[\s.()\-]*(?:공|영|일|이|삼|사|오|육|륙|칠|팔|구|[0-9])){7,8}(?![가-힣\d])/g, contact)
    .replace(/(?<!\d)(?:\d[\s-]*){13,19}(?!\d)/g, '[식별번호]')
    // 주소는 도로명+건물번호, 지번(번지·본번-부번), 아파트 동·호처럼 숫자가 붙은 형태만 본다. "둘레길 1구간"·"연남동 1번 출구"는 남긴다
    .replace(/(?:[가-힣]+(?:특별시|광역시|특별자치시|특별자치도|도|시|군|구)\s*)?(?:[가-힣\d]+(?:시|군|구|읍|면|동|리)\s*)*(?:[가-힣\d]+(?:로|길)\s*\d+(?:-\d+)?(?![\d가-힣])(?:\s*\d+\s*동)?(?:\s*\d+\s*호)?|[가-힣\d]+(?:동|리)\s*\d+(?:-\d+|\s*번지)(?:\s*\d+\s*호)?|\d+\s*동\s*\d+\s*호)/g, '[주소]')
    .replace(/((?:주소|거주지|집주소)\s*(?:은|는|이|가|:|：)\s*)[^,\n.!?]+/g, '$1[주소]')
    // 이름은 밝힌 문맥에서만 가린다. 성씨로 짐작하면 "마음이"·"하늘이" 같은 일상어가 대부분 가려져 검수·편지가 흐려진다
    .replace(/((?:이름|성명|본명)\s*(?:은|는|:|：)\s*)[가-힣]{2,4}/g, '$1[이름]')
    .replace(/((?:저는|나는)\s+)[가-힣]{3}(?=(?:입니다|이에요|이고|이라고))/g, '$1[이름]')
    .replace(/(?<![가-힣])(?!(?:선생|사장|기사|부장|과장|팀장|대리|교수|의사|간호사|친구|고객|회원|작가|선배|후배|이웃|어머|아버|할머|할아버|형|누)(?:님|씨))[가-힣]{2,4}(?=(?:님|씨)(?:[\s,.!?]|$))/g, '[이름]');
  return { text, hasContact };
}

export function filterNoteTexts<T extends { text: string | null }>(notes: T[]) {
  return notes.map((note) => ({ ...note, text: note.text === null ? null : filterModerationText(note.text).text }));
}
